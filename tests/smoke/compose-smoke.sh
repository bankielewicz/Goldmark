# --- Recovery: the generated administrator's volume is lost (docs/ops/database-recovery.md) --
# sa is disabled, so without the administrator's file nobody can sign in as sysadmin. Measured on
# the pinned image: mssql-conf set-sa-password, run against the stopped server's data volume, sets
# the password AND re-enables sa; the next db-init then resets the same administrator and
# disables sa again. The migration login's file shares that volume and is regenerated too.
old_admin_password="${admin_password}"; old_migration_password="${migration_password}"
"${compose[@]}" logs --no-color db-init > "${work}/db-init-before-recovery.log" 2>&1
"${compose[@]}" stop >/dev/null 2>&1

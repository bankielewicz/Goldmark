lockout_log="$("${compose[@]}" logs --no-color --no-log-prefix db-init 2>&1)"
if [[ "$(docker inspect -f '{{.State.ExitCode}}' "${project}-db-init-1")" == 1 && "${lockout_log}" == *"SQL Server error 18470"* \
      && "${lockout_log}" == *"docs/ops/database-recovery.md: re-enable sa with mssql-conf"* ]]; then
  pass "with the administrator's volume lost and sa disabled, db-init stops at once and names the recovery"
else
  fail "with the administrator's volume lost and sa disabled, db-init stops at once and names the recovery" "$(tail -n 3 <<< "${lockout_log}" | cut -c1-300)"

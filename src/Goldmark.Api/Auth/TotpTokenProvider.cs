using Microsoft.AspNetCore.Identity;

namespace Goldmark.Api.Auth;

/// <summary>
/// Identity's authenticator token provider, replaced at its plug-in point (owner, DEC-040): Identity's
/// own accepts two time steps either side and the same code more than once. This one accepts the current
/// step or one either side, and records the step so a code works once. It is registered as
/// <c>IdentityOptions.Tokens.AuthenticatorTokenProvider</c>, so <c>VerifyTwoFactorTokenAsync</c> uses it.
/// </summary>
internal sealed class TotpTokenProvider(TimeProvider time) : IUserTwoFactorTokenProvider<GoldmarkUser>
{
    public const string Name = "GoldmarkTotp";

    public Task<bool> CanGenerateTwoFactorTokenAsync(UserManager<GoldmarkUser> manager, GoldmarkUser user) =>
        Task.FromResult(user.HasAuthenticator);

    /// <summary>Codes come from the person's authenticator app; the server never generates one.</summary>
    public Task<string> GenerateAsync(string purpose, UserManager<GoldmarkUser> manager, GoldmarkUser user) =>
        throw new NotSupportedException("Authenticator codes are generated by the authenticator app.");

    public Task<bool> ValidateAsync(string purpose, string token, UserManager<GoldmarkUser> manager, GoldmarkUser user) =>
        ((GoldmarkUserManager)manager).VerifyAuthenticatorCodeAsync(user, token, time.GetUtcNow());
}

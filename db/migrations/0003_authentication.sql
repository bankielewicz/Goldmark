-- 0003 authentication (slice 3; US-02, US-03, US-04; DEC-038, DEC-040): user accounts, roles,
-- recovery codes, invitation and two-factor reset links, server-side sessions, and the row that
-- marks first-run setup as done.
--
-- Forward-only and immutable once merged (db/migrations.sha256, DEC-028). Every table is in schema
-- cmdb, so goldmark_runtime's schema-level DML grant (0002) covers it; nothing here grants more.
-- No secret is stored in a usable form: passwords and recovery codes are PBKDF2 hashes (ASP.NET Core
-- Identity's password hasher), link tokens and session keys are SHA-256 hashes of 256-bit random
-- values, and authenticator keys and session tickets are encrypted with ASP.NET Core Data
-- Protection, whose keys are outside the database (NFR-SEC-5).

-- The five roles of US-04. Collector is for service identities with API tokens (slices 8 and 13),
-- never for a person: cmdb.UserRole refuses it (DEC-038, item 10).
CREATE TABLE cmdb.Role
(
    Name varchar(20) NOT NULL CONSTRAINT PK_Role PRIMARY KEY
);

INSERT INTO cmdb.Role (Name) VALUES ('Admin'), ('Editor'), ('Viewer'), ('Auditor'), ('Collector');

-- A person who signs in. An invited person's account exists from the invitation on, with no
-- password and no authenticator until they redeem it. Id is a UUID v7 generated by the application.
CREATE TABLE cmdb.UserAccount
(
    Id                   uniqueidentifier  NOT NULL CONSTRAINT PK_UserAccount PRIMARY KEY,
    UserName             nvarchar(64)      NOT NULL,
    -- Upper-case invariant form (Identity's lookup normalizer); unique, so names differ in more than case.
    NormalizedUserName   nvarchar(64)      NOT NULL CONSTRAINT UQ_UserAccount_NormalizedUserName UNIQUE,
    DisplayName          nvarchar(200)     NOT NULL,
    PasswordHash         nvarchar(256)     NULL,
    -- Changes whenever credentials change; the pending sign-in and enrolment cookies carry it.
    SecurityStamp        nvarchar(64)      NOT NULL,
    -- Optimistic concurrency for every update; also the ETag of the user (If-Match, 412).
    ConcurrencyStamp     nvarchar(64)      NOT NULL,
    -- Identity's lockout: automatic after failures, or the largest value for an administrator's lock.
    LockoutEnd           datetimeoffset(7) NULL,
    AccessFailedCount    int               NOT NULL CONSTRAINT DF_UserAccount_AccessFailedCount DEFAULT (0),
    AuthenticatorKey     nvarchar(1024)    NULL,
    AuthenticatorSetUpAt datetime2(7)      NULL,
    -- The newest TOTP time step accepted, so a code is never accepted twice.
    LastTotpTimeStep     bigint            NULL,
    IsDisabled           bit               NOT NULL CONSTRAINT DF_UserAccount_IsDisabled DEFAULT (0),
    CreatedAt            datetime2(7)      NOT NULL CONSTRAINT DF_UserAccount_CreatedAt DEFAULT (SYSUTCDATETIME()),
    -- Null for the first administrator, who is created by first-run setup.
    CreatedBy            uniqueidentifier  NULL CONSTRAINT FK_UserAccount_CreatedBy REFERENCES cmdb.UserAccount (Id),
    LastSignInAt         datetime2(7)      NULL,
    CONSTRAINT CK_UserAccount_AccessFailedCount CHECK (AccessFailedCount >= 0),
    CONSTRAINT CK_UserAccount_Authenticator CHECK ((AuthenticatorKey IS NULL AND AuthenticatorSetUpAt IS NULL)
        OR (AuthenticatorKey IS NOT NULL AND AuthenticatorSetUpAt IS NOT NULL))
);

CREATE TABLE cmdb.UserRole
(
    UserId uniqueidentifier NOT NULL
        CONSTRAINT FK_UserRole_User REFERENCES cmdb.UserAccount (Id) ON DELETE CASCADE,
    Role   varchar(20)      NOT NULL CONSTRAINT FK_UserRole_Role REFERENCES cmdb.Role (Name),
    CONSTRAINT PK_UserRole PRIMARY KEY (UserId, Role),
    CONSTRAINT CK_UserRole_NotCollector CHECK (Role <> 'Collector')
);

-- Ten single-use recovery codes per person, issued once (US-03). A new set replaces the old one.
CREATE TABLE cmdb.RecoveryCode
(
    Id        bigint           NOT NULL IDENTITY(1, 1) CONSTRAINT PK_RecoveryCode PRIMARY KEY,
    UserId    uniqueidentifier NOT NULL
        CONSTRAINT FK_RecoveryCode_User REFERENCES cmdb.UserAccount (Id) ON DELETE CASCADE,
    CodeHash  nvarchar(256)    NOT NULL,
    CreatedAt datetime2(7)     NOT NULL CONSTRAINT DF_RecoveryCode_CreatedAt DEFAULT (SYSUTCDATETIME()),
    UsedAt    datetime2(7)     NULL
);

CREATE INDEX IX_RecoveryCode_User ON cmdb.RecoveryCode (UserId) INCLUDE (UsedAt);

-- A one-time link plus a separate short code (DEC-038, items 2 and 8), for an invitation or a
-- two-factor reset. The link's token travels in the URL fragment and is stored only as its SHA-256
-- hash; the code is stored as SHA-256(token, code), so it cannot be tried without the token. Five
-- wrong codes revoke the link. One open link per person: issuing a new one revokes the old one.
CREATE TABLE cmdb.UserInvitation
(
    Id                 uniqueidentifier NOT NULL CONSTRAINT PK_UserInvitation PRIMARY KEY,
    UserId             uniqueidentifier NOT NULL
        CONSTRAINT FK_UserInvitation_User REFERENCES cmdb.UserAccount (Id) ON DELETE CASCADE,
    Purpose            varchar(20)      NOT NULL
        CONSTRAINT CK_UserInvitation_Purpose CHECK (Purpose IN ('Invitation', 'TwoFactorReset')),
    TokenHash          binary(32)       NOT NULL CONSTRAINT UQ_UserInvitation_TokenHash UNIQUE,
    CodeHash           binary(32)       NOT NULL,
    FailedCodeAttempts tinyint          NOT NULL CONSTRAINT DF_UserInvitation_FailedCodeAttempts DEFAULT (0),
    CreatedAt          datetime2(7)     NOT NULL CONSTRAINT DF_UserInvitation_CreatedAt DEFAULT (SYSUTCDATETIME()),
    CreatedBy          uniqueidentifier NOT NULL CONSTRAINT FK_UserInvitation_CreatedBy REFERENCES cmdb.UserAccount (Id),
    ExpiresAt          datetime2(7)     NOT NULL,
    RedeemedAt         datetime2(7)     NULL,
    RevokedAt          datetime2(7)     NULL,
    CONSTRAINT CK_UserInvitation_Closed CHECK (RedeemedAt IS NULL OR RevokedAt IS NULL)
);

CREATE UNIQUE INDEX UX_UserInvitation_Open ON cmdb.UserInvitation (UserId)
    WHERE RedeemedAt IS NULL AND RevokedAt IS NULL;

-- Server-side sessions behind the sign-in cookie (DEC-040): the cookie holds only a random key,
-- stored here as its SHA-256 hash, so signing out, an administrator's action or a two-factor reset
-- ends the session on the server. Sessions end after 30 minutes idle or 12 hours (DEC-038, item 6).
CREATE TABLE cmdb.UserSession
(
    Id                binary(32)       NOT NULL CONSTRAINT PK_UserSession PRIMARY KEY,
    UserId            uniqueidentifier NOT NULL
        CONSTRAINT FK_UserSession_User REFERENCES cmdb.UserAccount (Id) ON DELETE CASCADE,
    Ticket            varbinary(max)   NOT NULL,
    CreatedAt         datetime2(7)     NOT NULL,
    LastSeenAt        datetime2(7)     NOT NULL,
    ExpiresAt         datetime2(7)     NOT NULL,
    AbsoluteExpiresAt datetime2(7)     NOT NULL,
    CONSTRAINT CK_UserSession_Expiry CHECK (ExpiresAt <= AbsoluteExpiresAt)
);

CREATE INDEX IX_UserSession_User ON cmdb.UserSession (UserId);
CREATE INDEX IX_UserSession_ExpiresAt ON cmdb.UserSession (ExpiresAt);

-- One row, written when first-run setup completes (US-02: the setup page is disabled permanently
-- after use). The application may add it but never change or remove it.
CREATE TABLE cmdb.Installation
(
    Id               tinyint          NOT NULL CONSTRAINT PK_Installation PRIMARY KEY
        CONSTRAINT CK_Installation_Single CHECK (Id = 1),
    SetupCompletedAt datetime2(7)     NOT NULL CONSTRAINT DF_Installation_SetupCompletedAt DEFAULT (SYSUTCDATETIME()),
    SetupCompletedBy uniqueidentifier NOT NULL CONSTRAINT FK_Installation_SetupCompletedBy REFERENCES cmdb.UserAccount (Id)
);

DENY UPDATE, DELETE ON OBJECT::cmdb.Installation TO goldmark_runtime;

-- 0010 API tokens (slice 8; US-06, US-07, NFR-SEC-5; DEC-048): scoped, expiring tokens with which scripts call
-- /api/v1 without a session.
--
-- Forward-only and immutable once merged (db/migrations.sha256, DEC-028). The table is in schema cmdb, so
-- goldmark_runtime's schema-level DML grant (0002) covers it; nothing here grants more.
-- No secret is stored in a usable form (NFR-SEC-5): a token's secret ("sxt_" and 43 letters and digits, from 32
-- random bytes) is kept only as the SHA-256 of the whole text, with its last four characters to recognise it by.

-- A token acts as itself, never as the Admin who created it (DEC-048): the audit log names it (actor type 'Token')
-- and the ChangedBy of what it writes holds 'token:' and its ID. Tokens are never deleted, so their names keep
-- resolving after they are revoked or expired. Id is a UUID v7 generated by the application.
CREATE TABLE cmdb.ApiToken
(
    Id             uniqueidentifier NOT NULL CONSTRAINT PK_ApiToken PRIMARY KEY,
    Name           nvarchar(100)    NOT NULL,
    -- Trimmed, upper-case invariant form (as UserAccount.NormalizedUserName): names are unique among all tokens,
    -- revoked and expired ones too, ignoring case and surrounding spaces.
    NormalizedName nvarchar(100)    NOT NULL CONSTRAINT UQ_ApiToken_NormalizedName UNIQUE,
    -- SHA-256 of the whole secret, by which a request's token is found.
    Hash           binary(32)       NOT NULL CONSTRAINT UQ_ApiToken_Hash UNIQUE,
    LastFour       char(4)          NOT NULL,
    -- The scope names, as a JSON array (this slice: cis:read, cis:write, relationships:read, relationships:write).
    Scopes         nvarchar(400)    NOT NULL CONSTRAINT CK_ApiToken_Scopes CHECK (ISJSON(Scopes, ARRAY) = 1),
    CreatedAt      datetime2(7)     NOT NULL CONSTRAINT DF_ApiToken_CreatedAt DEFAULT (SYSUTCDATETIME()),
    CreatedBy      uniqueidentifier NOT NULL CONSTRAINT FK_ApiToken_CreatedBy REFERENCES cmdb.UserAccount (Id),
    -- Every token expires (US-06), within a year of its creation (DEC-048 item 5); the database's clock judges it.
    ExpiresAt      datetime2(7)     NOT NULL,
    RevokedAt      datetime2(7)     NULL,
    RevokedBy      uniqueidentifier NULL CONSTRAINT FK_ApiToken_RevokedBy REFERENCES cmdb.UserAccount (Id),
    -- The last request the token authenticated, written at most once a minute; and when its use was last written to
    -- the audit log ("API token used"), at most once an hour (DEC-048).
    LastUsedAt     datetime2(7)     NULL,
    UseRecordedAt  datetime2(7)     NULL
);

-- A token's usage (screen 18) and the audit log's actor filter (actor=token:{id}, or a person's ID) read one actor's
-- entries, newest first. The audit log had only its indexes on At (0001) and on the target (0009). The app compares
-- ActorId as the text AuditTrail writes, a lower-case GUID, so this index can be sought; At and Action are included for
-- the screen's time and action filters, which come with the actor's.
CREATE INDEX IX_AuditLog_Actor ON cmdb.AuditLog (ActorType, ActorId, Id DESC)
    INCLUDE (At, Action);

-- 0001 baseline (slice 2, PRD §9.2): tenant, CI and relationship types, CIs and
-- relationships (system-versioned), audit log.
--
-- Forward-only and immutable once merged: never edit this file, add a new script
-- instead (db/migrations.sha256, DEC-028). DbUp runs each script in its own
-- transaction, as goldmark_migrator (db_owner of this database only).
--
-- Every schema object is owned by dbo, never by the migration login, so that
-- login can be replaced without touching ownership.

CREATE SCHEMA cmdb AUTHORIZATION dbo;
GO

-- Single row in the MVP; the schema is tenant-aware from day one (PRD §1.3).
CREATE TABLE cmdb.Tenant
(
    Id   uniqueidentifier NOT NULL CONSTRAINT PK_Tenant PRIMARY KEY,
    Name nvarchar(200)    NOT NULL CONSTRAINT UQ_Tenant_Name UNIQUE
);

INSERT INTO cmdb.Tenant (Id, Name) VALUES ('00000000-0000-0000-0000-000000000001', N'Default');

-- Built-in types are seeded with the CI model (slice 5, US-10).
CREATE TABLE cmdb.CiType
(
    Id           int           NOT NULL IDENTITY(1, 1) CONSTRAINT PK_CiType PRIMARY KEY,
    Name         nvarchar(100) NOT NULL CONSTRAINT UQ_CiType_Name UNIQUE,
    ParentTypeId int           NULL CONSTRAINT FK_CiType_Parent REFERENCES cmdb.CiType (Id),
    IsBuiltIn    bit           NOT NULL CONSTRAINT DF_CiType_IsBuiltIn DEFAULT (0),
    Icon         nvarchar(100) NULL
);

-- FR-CM-1/5. Id is a UUID v7 generated by the application. Owners are Team/Person CIs (US-13).
CREATE TABLE cmdb.Ci
(
    Id             uniqueidentifier NOT NULL CONSTRAINT PK_Ci PRIMARY KEY,
    TenantId       uniqueidentifier NOT NULL CONSTRAINT FK_Ci_Tenant REFERENCES cmdb.Tenant (Id),
    CiTypeId       int              NOT NULL CONSTRAINT FK_Ci_CiType REFERENCES cmdb.CiType (Id),
    Name           nvarchar(400)    NOT NULL,
    LifecycleState varchar(10)      NOT NULL
        CONSTRAINT CK_Ci_LifecycleState CHECK (LifecycleState IN ('Planned', 'Active', 'Retiring', 'Retired')),
    OwnerTeamId    uniqueidentifier NULL CONSTRAINT FK_Ci_OwnerTeam REFERENCES cmdb.Ci (Id),
    OwnerPersonId  uniqueidentifier NULL CONSTRAINT FK_Ci_OwnerPerson REFERENCES cmdb.Ci (Id),
    Attributes     json             NOT NULL CONSTRAINT DF_Ci_Attributes DEFAULT ('{}'),
    ContentHash    binary(32)       NULL,
    ChangedBy      nvarchar(256)    NOT NULL,
    ValidFrom      datetime2(7) GENERATED ALWAYS AS ROW START NOT NULL,
    ValidTo        datetime2(7) GENERATED ALWAYS AS ROW END NOT NULL,
    PERIOD FOR SYSTEM_TIME (ValidFrom, ValidTo)
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = cmdb.CiHistory, DATA_CONSISTENCY_CHECK = ON));

CREATE INDEX IX_Ci_Tenant_Type ON cmdb.Ci (TenantId, CiTypeId);
CREATE INDEX IX_Ci_Tenant_Name ON cmdb.Ci (TenantId, Name);

-- FR-CM-6, §5.5. Direction is always dependent -> dependency.
CREATE TABLE cmdb.RelationshipType
(
    Id                int           NOT NULL IDENTITY(1, 1) CONSTRAINT PK_RelationshipType PRIMARY KEY,
    Name              nvarchar(100) NOT NULL CONSTRAINT UQ_RelationshipType_Name UNIQUE,
    FromCiTypeId      int           NULL CONSTRAINT FK_RelationshipType_FromCiType REFERENCES cmdb.CiType (Id),
    ToCiTypeId        int           NULL CONSTRAINT FK_RelationshipType_ToCiType REFERENCES cmdb.CiType (Id),
    ImpactPropagation varchar(10)   NOT NULL
        CONSTRAINT CK_RelationshipType_ImpactPropagation CHECK (ImpactPropagation IN ('None', 'Down')),
    IsBuiltIn         bit           NOT NULL CONSTRAINT DF_RelationshipType_IsBuiltIn DEFAULT (0)
);

-- FR-CM-5/6. SourceId gets its foreign key when the Source table exists (slice 13).
CREATE TABLE cmdb.Relationship
(
    Id                 uniqueidentifier NOT NULL CONSTRAINT PK_Relationship PRIMARY KEY,
    TenantId           uniqueidentifier NOT NULL CONSTRAINT FK_Relationship_Tenant REFERENCES cmdb.Tenant (Id),
    FromCiId           uniqueidentifier NOT NULL CONSTRAINT FK_Relationship_FromCi REFERENCES cmdb.Ci (Id),
    ToCiId             uniqueidentifier NOT NULL CONSTRAINT FK_Relationship_ToCi REFERENCES cmdb.Ci (Id),
    RelationshipTypeId int              NOT NULL CONSTRAINT FK_Relationship_Type REFERENCES cmdb.RelationshipType (Id),
    RedundancyGroup    nvarchar(200)    NULL,
    SourceId           uniqueidentifier NULL,
    ContentHash        binary(32)       NULL,
    ChangedBy          nvarchar(256)    NOT NULL,
    ValidFrom          datetime2(7) GENERATED ALWAYS AS ROW START NOT NULL,
    ValidTo            datetime2(7) GENERATED ALWAYS AS ROW END NOT NULL,
    PERIOD FOR SYSTEM_TIME (ValidFrom, ValidTo),
    CONSTRAINT CK_Relationship_NotSelf CHECK (FromCiId <> ToCiId),
    CONSTRAINT UQ_Relationship UNIQUE (FromCiId, RelationshipTypeId, ToCiId)
)
WITH (SYSTEM_VERSIONING = ON (HISTORY_TABLE = cmdb.RelationshipHistory, DATA_CONSISTENCY_CHECK = ON));

CREATE INDEX IX_Relationship_ToCi ON cmdb.Relationship (ToCiId, RelationshipTypeId);

-- US-07, NFR-SEC-4. Append-only for the application: 0002 denies UPDATE and DELETE.
CREATE TABLE cmdb.AuditLog
(
    Id         bigint        NOT NULL IDENTITY(1, 1) CONSTRAINT PK_AuditLog PRIMARY KEY,
    At         datetime2(7)  NOT NULL CONSTRAINT DF_AuditLog_At DEFAULT (SYSUTCDATETIME()),
    ActorType  varchar(20)   NOT NULL,
    ActorId    nvarchar(256) NULL,
    Action     varchar(100)  NOT NULL,
    TargetType varchar(50)   NULL,
    TargetId   nvarchar(256) NULL,
    Ip         varchar(45)   NULL,
    Details    json          NULL
);

CREATE INDEX IX_AuditLog_At ON cmdb.AuditLog (At);
